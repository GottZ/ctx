@pytest.mark.parametrize("name", sorted(CASES))
def test_golden_render(a, name):
    out = a.assemble(**CASES[name], channel_id=CHANNEL_ID, budget=9500)
    assert out.text == GOLDEN[name]
    assert out.length == len(GOLDEN[name]) <= 9500


def test_golden_metadata(a):
    meta = {name: a.assemble(**CASES[name], channel_id=CHANNEL_ID, budget=9500) for name in CASES}
    assert {name: m.guidance for name, m in meta.items()} == {
        "public_ambient": "included",
        "public_direct_german": "empty",
        "operator_direct_guidance_off": "excluded_operator_lane",
        "operator_worklog_guidance_on": "included",
    }
    assert meta["operator_worklog_guidance_on"].placeholders == {
        "bot_name": "Bolt", "server_name": "Example Guild", "channel_name": "general",
        "channel": f"<#{CHANNEL_ID}>", "language": "English", "worklog_channel": f"<#{WORKLOG_ID}>",
        "operator_label": "the host",
    }
    # operator turn without server guidance: the managers' bot name and language are not used either
    assert meta["operator_direct_guidance_off"].placeholders["bot_name"] == "Pixel"
    assert meta["operator_direct_guidance_off"].placeholders["language"] == "the language of the message"


def test_golden_shortened_guidance(a):
    case = dict(CASES["public_ambient"])
    bare = a.assemble(**{**case, "guild": guild()}, channel_id=CHANNEL_ID, budget=9500)
    rules = "\n".join(f"Rule {i}: keep it civil and on topic." for i in range(1, 21))
    out = a.assemble(**{**case, "guild": guild(rules)}, channel_id=CHANNEL_ID, budget=bare.length + 450)
    assert out.text == bare.text + SHORTENED_TAIL
    assert (out.guidance, out.truncated_by, out.guidance_chars, out.guidance_rendered_chars,
            out.guidance_chars_used) == ("shortened", ("budget",), len(rules), len(rules),
                                         len("Rule 1: keep it civil and on topic."))
    assert out.length <= bare.length + 450


def test_golden_reaction_wakeup(a):
    assert a.reaction_wakeup_text({}, guild()) == (
        "[REACTION WAKEUP] Reply to the referenced message using only the context of this Discord server.")
