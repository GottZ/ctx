def guild(guidance="", *, bot_name="Pixel", language="the language of the message", worklog=None,
          in_operator_lane=False, overrides=None):
    return {
        "identity": {"bot_name": bot_name, "wake_names": [], "greetings": [], "reaction_emoji": None},
        "conversation": {"ambient_channels": [], "excluded_channels": [], "language": language},
        "worklog": {"channel": worklog, "archive_minutes": 1440, "final_to_origin": True},
        "prompts": {"guild": guidance, "guild_in_operator_lane": in_operator_lane, "history": [],
                    "template_overrides": overrides or {}},
    }


